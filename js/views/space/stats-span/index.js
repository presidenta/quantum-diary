/* СРОК СВОДКИ ХРОНИК (выкладка 232) — что значит каждый вариант в списке под табами и как он подписан.
   Зачем и как подключено — README.md рядом. */

const СУТКИ = 24 * 60 * 60 * 1000;

/* Варианты каждого таба. Код — единица и число: d — дни, w — недели, m — месяцы, y — годы; all — всё время.
   Владелец 11.11.2026: «неделя — за 1, 2 … 7 дней; месяц — за 1 … 4 недели; всё время — по месяцам до шести и год». */
export const SPAN_TABS = {
    week: ['d1', 'd2', 'd3', 'd4', 'd5', 'd6', 'd7'],
    month: ['w1', 'w2', 'w3', 'w4'],
    all: ['m1', 'm2', 'm3', 'm4', 'm5', 'm6', 'y1', 'all']
};

/* Вариант, при котором таб подписан по-старому: «За неделю», «За месяц», «За всё время». До 232 в памяти лежали
   сами имена табов — они переводятся в эти же варианты, и выбор человека не теряется. */
export const SPAN_DEFAULT = { week: 'd7', month: 'w4', all: 'all' };

export function parseSpan(сохранённый) {
    if (SPAN_DEFAULT[сохранённый]) return SPAN_DEFAULT[сохранённый];
    return spanTab(сохранённый) ? сохранённый : 'all';
}

export function spanTab(span) {
    return Object.keys(SPAN_TABS).find(таб => SPAN_TABS[таб].includes(span)) || null;
}

/* Начало срока. Дни и недели — ровно столько суток назад. Месяцы и год — по календарю: «за 1 месяц» 11 ноября —
   с 11 октября. Если такого числа в том месяце нет (31 марта минус месяц), берётся последнее число месяца, а не
   переползание на 3 марта. */
export function spanSince(span, now = Date.now()) {
    if (span === 'all') return 0;
    const единица = span[0];
    const n = Number(span.slice(1));
    if (единица === 'd') return now - n * СУТКИ;
    if (единица === 'w') return now - n * 7 * СУТКИ;
    const дата = new Date(now);
    const число = дата.getDate();
    дата.setDate(1);
    if (единица === 'm') дата.setMonth(дата.getMonth() - n);
    else дата.setFullYear(дата.getFullYear() - n);
    const последнее = new Date(дата.getFullYear(), дата.getMonth() + 1, 0).getDate();
    дата.setDate(Math.min(число, последнее));
    return дата.getTime();
}

/* Прошлый срок для серой полоски — такой же длины, вплотную перед нынешним: за 3 дня сравниваются с тремя днями
   до них, за полгода — с полугодом до него. Всё время сравнивать не с чем. Прошлый срок начинается раньше
   «Сброса» — тоже нет: старый отсчёт с новым не смешиваем (как с 187). */
export function spanBefore(span, now = Date.now(), сброс = 0) {
    if (span === 'all') return null;
    const since = spanSince(span, now);
    const окно = { since: since - (now - since), until: since };
    return сброс > окно.since ? null : окно;
}

// Склонение для русского и украинского: 1, 2–4, 5 и больше (11–14 — тоже «много»)
function форма(n, [одна, несколько, много]) {
    const сотни = n % 100;
    const десятки = n % 10;
    if (сотни > 10 && сотни < 20) return много;
    if (десятки === 1) return одна;
    if (десятки >= 2 && десятки <= 4) return несколько;
    return много;
}

const СЛОВА = {
    ru: {
        all: 'За всё время',
        d: ['день', 'дня', 'дней'], w: ['неделю', 'недели', 'недель'], m: ['месяц', 'месяца', 'месяцев'], y: ['год', 'года', 'лет'],
        за: n => `За ${n}`,
        // «за предыдущую неделю», «за предыдущие 3 дня» — во множественном те же формы, что выше
        прошлый: { d: 'предыдущие сутки', w: 'предыдущую неделю', m: 'предыдущий месяц', y: 'предыдущий год' },
        прошлые: 'предыдущие'
    },
    uk: {
        all: 'За весь час',
        d: ['день', 'дні', 'днів'], w: ['тиждень', 'тижні', 'тижнів'], m: ['місяць', 'місяці', 'місяців'], y: ['рік', 'роки', 'років'],
        за: n => `За ${n}`,
        прошлый: { d: 'попередню добу', w: 'попередній тиждень', m: 'попередній місяць', y: 'попередній рік' },
        прошлые: 'попередні'
    },
    en: {
        all: 'All time',
        d: ['day', 'days', 'days'], w: ['week', 'weeks', 'weeks'], m: ['month', 'months', 'months'], y: ['year', 'years', 'years'],
        за: n => `${n}`,
        прошлый: { d: 'the previous day', w: 'the previous week', m: 'the previous month', y: 'the previous year' },
        прошлые: 'the previous'
    }
};

const словаРечи = lang => СЛОВА[lang] || СЛОВА.ru;
const формаЯзыка = (lang, n, формы) => (lang === 'en' ? (n === 1 ? формы[0] : формы[1]) : форма(n, формы));

// Подпись варианта в списке: «За 3 дня», «За 2 недели», «За 6 месяцев», «За 1 год», «За всё время»
export function spanLabel(span, lang) {
    const слова = словаРечи(lang);
    if (span === 'all') return слова.all;
    const единица = span[0];
    const n = Number(span.slice(1));
    const текст = `${n} ${формаЯзыка(lang, n, слова[единица])}`;
    return слова.за(lang === 'en' ? текст.charAt(0).toUpperCase() + текст.slice(1) : текст);
}

/* Подпись выбранного срока на самом табе — без «За»: «3 дня», «2 недели», «6 месяцев». Таб узкий, на телефоне
   «За 2 недели» обрезалось до «За 2 не…»; что это срок, видно и так — он стоит на месте «За неделю». Месяцы по-русски
   и по-украински — «мес.» / «міс.»: «6 месяцев» в таб не влезало и тоже обрезалось. */
const МЕС = { ru: 'мес.', uk: 'міс.' };
export function spanShortLabel(span, lang) {
    if (span === 'all') return словаРечи(lang).all;
    const n = Number(span.slice(1));
    const слово = span[0] === 'm' && МЕС[lang] ? МЕС[lang] : формаЯзыка(lang, n, словаРечи(lang)[span[0]]);
    const текст = `${n} ${слово}`;
    return lang === 'en' ? текст.charAt(0).toUpperCase() + текст.slice(1) : текст;
}

// Прошлый срок для пояснения серой полоски: «предыдущие 3 дня», «предыдущую неделю»; для всего времени — пусто
export function spanPastLabel(span, lang) {
    if (span === 'all') return '';
    const слова = словаРечи(lang);
    const единица = span[0];
    const n = Number(span.slice(1));
    if (n === 1) return слова.прошлый[единица];
    return `${слова.прошлые} ${n} ${формаЯзыка(lang, n, слова[единица])}`;
}
