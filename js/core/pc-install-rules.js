/* Телефон или планшет по строке браузера.
   Mobile стоит в строке и у Android-телефонов, и у Chrome на планшете в
   обычном режиме; iPhone и iPad называют себя прямо. */
const ТЕЛЕФОН_ПО_СТРОКЕ = /Android|iPhone|iPad|iPod|Mobile|Windows Phone/i;

/**
 * Настольный ли это браузер.
 *
 * @param {object} среда
 * @param {string}  [среда.userAgent]
 * @param {boolean} [среда.uaMobile]       navigator.userAgentData.mobile; есть
 *                                         не везде, и тогда undefined
 * @param {number}  [среда.maxTouchPoints]
 * @param {boolean} [среда.coarsePointer]  главный указатель — палец
 */
export function isDesktopBrowser(среда = {}) {
    const { userAgent = '', uaMobile, maxTouchPoints = 0, coarsePointer = false } = среда;

    // Браузер сам говорит, что он на телефоне, — верим ему сразу
    if (uaMobile === true) return false;

    if (ТЕЛЕФОН_ПО_СТРОКЕ.test(userAgent)) return false;

    /* iPad с iPadOS 13 и новее называет себя Макинтошем. Отличить его
       можно только по касаниям: у настоящего Мака экран их не принимает.
       (То же правило, что в js/ios-home.js.) */
    if (/Macintosh/.test(userAgent) && maxTouchPoints > 1) return false;

    /* Планшет на Android в режиме «версия для компьютера» подставляет
       строку Линукса, и по ней его не узнать. Выдаёт его указатель:
       главный здесь палец. У ноутбука с сенсорным экраном главный
       указатель всё равно мышь или тачпад, и он остаётся компьютером. */
    if (coarsePointer) return false;

    return true;
}

/**
 * Предлагать ли кнопку «Установить на ПК».
 *
 * @param {object} среда  то же, что у isDesktopBrowser, и ещё:
 * @param {boolean} [среда.native]      страница открыта внутри приложения
 * @param {boolean} [среда.standalone]  уже открыта отдельным окном
 */
export function shouldOfferPcInstall(среда = {}) {
    if (среда.native) return false;       // внутри приложения ставить нечего
    if (среда.standalone) return false;   // уже установлено, окно своё
    return isDesktopBrowser(среда);
}
