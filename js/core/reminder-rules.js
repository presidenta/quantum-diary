/* ПРАВИЛА НАПОМИНАНИЙ: что должно позвонить и когда.

   Чистые правила без браузера, сети и плагинов — их можно проверить
   тестами, и они проверены (test/reminders.test.js). Всё, что требует
   телефона, живёт этажом выше, в js/reminder-plan.js: там читается
   состояние приложения и зовётся системный будильник.

   Решение здесь принимается в двух видах сразу: что ПОСТАВИТЬ и что
   СНЯТЬ. Второе не менее важно первого. Напоминание, поставленное вчера,
   живёт в системе само по себе и позвонит, даже если момент давно прожит
   или погашен крестиком, — снять его может только приложение, и только
   если знает, что именно снимать. */

import { observerClock } from './observer-clock.js';
import {
    isOff, activeMoment, nextMoment, timeNow, MOMENT_WINDOW_MINUTES
} from './quantum.js';

export const KEY_WINDOW = 'quantum-window';
export const KEY_MOMENT = 'moment-';

/* ВРЕМЯ СЛЕДУЮЩЕГО ЗВОНКА — две отдельные настройки, по одной под каждой
   галочкой в профиле. Человек ставит час, когда хочет, чтобы его окликнули:
   перемена, обед, перерыв. Ключи свои, не из расписания, — иначе этот
   звонок снимал бы настоящее напоминание или снимался вместе с ним. */
export const KEY_NEXT_WINDOW = 'alarm-next-window';
export const KEY_NEXT_MOMENTS = 'alarm-next-moments';

/* КЛЮЧИ СЛЕДУЮЩИХ ДНЕЙ.

   Названный час звонит каждый день, а не один раз (см. namedHorizon): на
   завтра и послезавтра ставятся копии со своими ключами — тот же ключ с
   суффиксом «+1», «+2». Свои ключи нужны потому, что у одного ключа в
   системе один будильник: вторая постановка с тем же ключом заменила бы
   первую, и звонка на завтра не оказалось бы.

   Для решений «чей это звонок» важен базовый ключ, без суффикса. */
export function baseKey(key) {
    const match = /^(alarm-next-(?:window|moments))\+\d+$/.exec(String(key));
    return match ? match[1] : String(key);
}

/* Про окно возможностей это напоминание или про момент дня.
   Нужно экрану: по нажатию на уведомление открывается своя вкладка. */
export const isWindowKey = key => {
    const base = baseKey(key);
    return base === KEY_WINDOW || base === KEY_NEXT_WINDOW;
};

/* Что может делать каждое из двух направлений. См. normalizeAlarm. */
export const РЕЖИМЫ_РАЗДЕЛА = Object.freeze(['alarm', 'remind', 'off']);

/* Время «ЧЧ:ММ» сегодняшнего дня как момент времени.

   Моменты приходят с сервера строкой без даты: день всегда сегодняшний.
   Непонятную строку возвращаем как null, а не как «полночь» — молчание
   лучше звонка в три часа ночи из-за испорченного поля. */
export function atToday(hhmm, now = new Date()) {
    const parts = String(hhmm).split(':');
    if (parts.length !== 2) return null;

    const h = Number(parts[0]);
    const m = Number(parts[1]);
    if (!Number.isInteger(h) || !Number.isInteger(m)) return null;
    if (h < 0 || h > 23 || m < 0 || m > 59) return null;

    const at = new Date(now);
    at.setHours(h, m, 0, 0);
    return at;
}

/* Минуты от полуночи. Время приходит строкой «ЧЧ:ММ» — так его отдаёт
   поле ввода времени и так его удобно хранить. */
export function minutesOfDay(hhmm) {
    const parts = String(hhmm).split(':');
    if (parts.length !== 2) return null;

    const h = Number(parts[0]);
    const m = Number(parts[1]);
    if (!Number.isInteger(h) || !Number.isInteger(m)) return null;
    if (h < 0 || h > 23 || m < 0 || m > 59) return null;

    return h * 60 + m;
}

/* Тихий час: промежуток, когда телефон молчит.

   Границы задаёт человек в профиле и приходят они сюда снаружи — правило
   не знает ни конкретных цифр, ни того, где они хранятся.

   Промежуток обычно переходит через полночь (с 22:00 до 7:00), и тогда
   проверка идёт на ИЛИ: 23:30 больше начала, 3:00 меньше конца — тихо и
   там, и там. Но человек вправе задать и дневной промежуток, скажем с
   13:00 до 15:00, — тогда работает обычное «между», на И. Поэтому две
   ветки, а не одна.

   Равные границы — это «тихо никогда», а не «тихо всегда». Так понятнее
   человеку: случайно выставив одинаковое время, он останется с рабочими
   напоминаниями, а не с мёртвой тишиной, причину которой потом не
   найдёт. */
export function isQuietTime(date, from, until) {
    const start = minutesOfDay(from);
    const end = minutesOfDay(until);
    if (start === null || end === null || start === end) return false;

    const now = date.getHours() * 60 + date.getMinutes();
    return start > end
        ? (now >= start || now < end)   // через полночь
        : (now >= start && now < end);  // внутри одних суток
}

/* Приводим что угодно к годной настройке тихого часа.

   Читаем мы её из хранилища телефона, а туда могла попасть и чепуха:
   запись от прежней версии, недописанное сохранение, правка руками.
   Поэтому каждое поле проверяется по отдельности и негодное заменяется
   начальным — одно испорченное значение не должно ронять напоминания
   целиком.

   Начальные значения приходят снаружи: правило не знает, какой час в
   этом приложении считается тихим по умолчанию. */
export function normalizeQuiet(raw, fallback) {
    const src = raw && typeof raw === 'object' ? raw : {};
    const годное = v => (minutesOfDay(v) === null ? null : v);

    return {
        on: src.on !== false,
        from: годное(src.from) || fallback.from,
        until: годное(src.until) || fallback.until
    };
}

/* Попадает ли срок в тихий час.

   Настройка приходит одним объектом {on, from, until} прямо из профиля.
   Выключена или не задана — тихого часа нет, и звонит всё. */
function underQuiet(at, quiet) {
    if (!quiet?.on) return false;
    return isQuietTime(at, quiet.from, quiet.until);
}

/* ДО КАКОГО ЧАСА ЗВОНОК ЕЩЁ ГОДИТСЯ, ЕСЛИ ОН ОПОЗДАЛ.

   Звонок здесь не точный, как у будильника: «после такого-то часа, на протяжении
   интервала». Момент дня живёт сорок минут (MOMENT_WINDOW_MINUTES), окно
   возможностей — столько, сколько оно открыто. Владелец 17.10.2026 сказал это
   прямо: если телефон разбудил приложение в 6:20, а час был 6:00, звонить надо
   и тогда — это нормально, лишь бы звонок был.

   Раньше приложение, проснувшись позже срока, записывало «не дошёл» и молчало.
   Теперь нативная часть, проснувшись по заданию, виджету, плитке или после
   перезагрузки, звонит, пока этот срок не вышел (AlarmRevive, раздел 9.23).

   Срок у каждого вида свой, поэтому считается по ключу:
     момент дня и час, названный для моментов — сорок минут;
     окно возможностей и час, названный для окна — сколько окно открыто;
     всё остальное (проверочные звонки) — не годится после срока, 0.

   ТИХИЙ ЧАС НЕ НАРУШАЕМ. Звонок со звуком не должен догнать человека ночью:
   срок кончается там, где начинается тишина. Беззвучному (quiet) это не
   мешает — он и так без звука.

   @param item     напоминание {key, at, quiet?}; at — Date или миллисекунды
   @param windowMs сколько открыто окно возможностей
   @param quiet    тихий час {on, from, until} или null
   @returns {number} миллисекунды, до которых звонок годен; 0 — после срока не звонит */
export function lateUntil(item, windowMs, quiet = null) {
    const key = String(item?.key ?? '');
    const at = item?.at instanceof Date ? item.at.getTime() : Number(item?.at);
    if (!Number.isFinite(at)) return 0;

    const base = baseKey(key);
    let срок = 0;
    if (base === KEY_WINDOW || base === KEY_NEXT_WINDOW) срок = Number(windowMs) || 0;
    else if (base.startsWith(KEY_MOMENT) || base === KEY_NEXT_MOMENTS) срок = MOMENT_WINDOW_MINUTES * 60 * 1000;
    if (!(срок > 0)) return 0;

    if (item.quiet || !quiet?.on) return at + срок;

    for (let минут = 1; минут * 60 * 1000 <= срок; минут++) {
        if (underQuiet(new Date(at + минут * 60 * 1000), quiet)) return at + минут * 60 * 1000;
    }
    return at + срок;
}

/* Моменты дня: что поставить, а что снять.

   Звонить стоит только о том моменте, который ещё впереди, ещё не прожит
   и не погашен крестиком. Обо всех остальных — снимать, и именно поэтому
   список снятия перечисляет их поимённо, а не молчит о них.

   ТИХИЙ ЧАС НЕ СНИМАЕТ НАПОМИНАНИЕ, А ГЛУШИТ ЕГО — правка 16.10.2026 по
   просьбе владельца, и прежнее поведение было другим.

   Прежде попавший в тишину момент снимался совсем: решили, что звонить о
   сорокаминутном моменте к утру всё равно поздно. Владелец же сказал
   прямо: «если человек сам выставил тихий час, приложение только отсылает
   напоминание без звука». Разница существенная: снятое напоминание не
   оставляет и следа, и человек, проснувшись, не узнаёт, что его звали. А
   беззвучная плашка дожидается его в шторке.

   Поэтому в тишину уходит не ключ, а признак: quiet: true. Напоминание
   ставится, но беззвучным каналом и никогда будильником — ни звука, ни
   вибрации, ни окна (см. разметитьРежим в web/js/reminder-plan.js и
   CHANNEL_QUIET в web/js/core/reminders.js).

   Снимается по-прежнему только то, чего уже нет: погашенное крестиком,
   прожитое и просроченное.

   base — день, к которому относятся часы «ЧЧ:ММ». По умолчанию это сегодня
   (now), и так работал весь код до выкладки 126. Для заготовки на завтра
   (см. provisionalDay) сюда передают завтрашнюю дату; «прошло ли» при этом
   по-прежнему меряется от now. */
export function momentPlan(moments, now = new Date(), quiet = null, alarm = null, base = now) {
    const ring = [];
    const silence = [];

    /* Архитектор выключен совсем — ни одного напоминания о моментах, и все
       их ключи уходят в снятие: поставленное раньше живёт в системе само
       по себе и прозвонило бы. */
    const выключен = alarm !== null && normalizeAlarm(alarm).momentsMode === 'off';

    for (const moment of Array.isArray(moments) ? moments : []) {
        const key = KEY_MOMENT + moment.id;
        const at = atToday(moment.at, base);

        if (выключен || isOff(moment) || moment.doneAt || !at || at.getTime() <= now.getTime()) {
            silence.push(key);
            continue;
        }
        ring.push(underQuiet(at, quiet) ? { key, at, quiet: true } : { key, at });
    }

    return { ring, silence };
}

/* РЕЖИМ АКТИВНОСТИ: что звонит будильником, а что остаётся плашкой.

   ОДНА ГАЛОЧКА ВМЕСТО ДВУХ — правка 16.10.2026, и она отменяет прежнее
   решение. Галочек было две: «окно возможностей» и отдельно «девять
   моментов дня», вторая выключена по умолчанию. Доводом было: девять
   будильников в день подряд — пытка, и включать их за человека нельзя.

   Довод оказался против человека. Владелец включил режим, назвал час — и
   получил беззвучную плашку, потому что звонила та галочка, которую он не
   нашёл. Настройка, о существовании которой надо догадаться, чтобы
   приложение заработало как обещано, — это не осторожность, а поломка.

   Модель теперь та, которую владелец назвал словами: «тихий час — только
   беззвучное напоминание; режим активности — окно поверх всех окон и
   звонок, пока не отключишь». Два состояния, и границу между ними задаёт
   тихий час, а не вторая галочка.

   on — режим активности. ВКЛЮЧЁН по умолчанию: звонок и есть то, ради
   чего ставят это приложение, а от ночного звонка защищает тихий час,
   который по умолчанию тоже включён. Сравнение «!== false», а не
   «=== true»: выключает только явное false, то есть собственное решение
   человека. Пустое хранилище и испорченная запись означают «как
   задумано», а не «молчать».

   Два поля времени (windowAt, momentsAt) остались: это два названных
   человеком часа, у каждого свой раздел. Галочки под ними больше нет —
   оба работают, пока включён режим активности.

   Решение здесь чистое и под тестами. Хранение и сам звонок — этажом
   выше (js/reminder-plan.js и js/core/reminders.js). */
export function normalizeAlarm(raw) {
    const src = raw && typeof raw === 'object' ? raw : {};
    // Негодное время — пустая строка, то есть «времени не задано».
    // Испорченное поле не должно ни ронять настройку, ни звонить невесть когда
    const время = v => (minutesOfDay(v) === null ? '' : v);
    const режим = (v, запасной) => (РЕЖИМЫ_РАЗДЕЛА.includes(v) ? v : запасной);

    return {
        on: src.on !== false,

        /* КАЖДОЕ НАПРАВЛЕНИЕ — СВОЁ, И У КАЖДОГО ТРИ СОСТОЯНИЯ.

           «Окно возможностей» (Наблюдатель) и «Девять моментов дня»
           (Архитектор) — два разных направления, и человек вправе
           пользоваться либо одним, либо другим, либо обоими сразу. Это
           просьба владельца от 16.10.2026, и она важнее удобства кода.

             alarm  — звонит будильником (по умолчанию);
             remind — только напоминание обычной плашкой, без звонка;
             off    — выключено совсем: ни звонка, ни напоминания.

           Три состояния, а не два, потому что просьб было две и обе
           законны: «чтобы были просто напоминания, чтобы будильник не
           звонил» и «одно полностью отключить, второе полностью
           использовать». Двух крестиков хватало на первую и не хватало на
           вторую: «выключенный» раздел продолжал слать плашки.

           По умолчанию оба — alarm. Негодное значение читается как alarm
           же: испорченная запись не должна молча выключать направление.

           ПЕРЕЕЗД СО СТАРЫХ ПОЛЕЙ. До этой правки были булевы windowOn и
           momentsOn (false = без звонка, но с напоминанием). Пока нового
           поля нет, они читаются и означают remind. */
        windowMode: режим(src.windowMode, src.windowOn === false ? 'remind' : 'alarm'),
        momentsMode: режим(src.momentsMode, src.momentsOn === false ? 'remind' : 'alarm'),

        /* ПЛАШКА В ШТОРКЕ — время следующих входов и две кнопки
           (android-alarm-plugin, AlarmPlashka). Поле называется guardOn по
           старой памяти: раньше это был «страж» — служба, державшая
           приложение живым, и от неё отказались (раздел 9.18). Включена по
           умолчанию; выключает только явное false — то же правило, что у
           крестиков. */
        guardOn: src.guardOn !== false,

        windowAt: время(src.windowAt),
        momentsAt: время(src.momentsAt),

        /* Когда час Наблюдателя назначен (мс). Нужен часам Наблюдателя: назначенный час
           следует за циклом, только если он уже прозвенел ПОСЛЕ того, как его назначили
           (cycleNamedHour в core/observer-clock.js), — иначе автоматика затёрла бы час,
           который человек только что поставил на вечер. */
        windowSetAt: Number(src.windowSetAt) > 0 ? Number(src.windowSetAt) : 0
    };
}

/* Ближайшее наступление времени «ЧЧ:ММ».
 *
 * Сегодня, если этот час ещё впереди, иначе завтра. Именно «следующий
 * звонок» человек и задаёт: поставив 13:00 в два часа дня, он имеет в
 * виду завтрашний обед, а не мгновенный звонок и не тишину.
 *
 * Непонятное время — null, а не полночь: молчание лучше звонка в три
 * ночи из-за испорченного поля (то же правило, что у atToday). */
export function atNext(hhmm, now = new Date()) {
    const минуты = minutesOfDay(hhmm);
    if (минуты === null) return null;

    const at = new Date(now);
    at.setHours(Math.floor(минуты / 60), минуты % 60, 0, 0);
    if (at.getTime() <= now.getTime()) at.setDate(at.getDate() + 1);
    return at;
}

/* ЧТО ПОСТАВИТЬ И ЧТО СНЯТЬ ПО ЗАДАННОМУ ВРЕМЕНИ.
 *
 * Поле пустое — ключ попадает в снятие, а не просто пропускается. Это не
 * мелочь: человек стёр время, а поставленный вчера будильник живёт в
 * системе сам по себе и прозвонит, если его не снять. То же правило, что
 * у моментов дня.
 *
 * Время работает только при включённой галочке, под которой стоит: своё
 * у окна возможностей, своё у девяти моментов дня. Галочка выключена —
 * этот источник не звонит будильником вовсе, и время от него не должно
 * звонить тоже.
 *
 * ТИХИЙ ЧАС ЗДЕСЬ НЕ ДЕЙСТВУЕТ, и это сознательно. Тихий час защищает от
 * того, что приложение назначило само. А этот час человек назвал сам, и
 * промолчать в ответ было бы хуже: он ждёт звонка и не узнает, почему его
 * не было. */
/* Сколько минут ПОСЛЕ назначенного часа будильник неприкосновенен.

   Зачем защита вообще. Прозвонил первый звонок, человек нажал кнопку,
   приложение открылось — и пересчитало расписание. А час второго к
   этому мигу уже прошёл, хоть на полминуты, и тот честно уехал на
   завтра. Снаружи: «верхний сработал, нижний нет». Беда общая: любое
   открытие приложения сразу после срабатывания съедало только что
   прозвонивший будильник.

   ПОЧЕМУ ТОЛЬКО ПОСЛЕ, А НЕ В ОБЕ СТОРОНЫ. Сначала защита стояла в обе
   стороны — и сама же всё сломала. Человек ставит звонок на минуту
   вперёд, сохраняет, а тот попадает в «не трогать» и не ставится вовсе:
   защищать было нечего, в системе его ещё не было. Ни один звонок,
   назначенный на ближайшие минуты, не срабатывал.

   Отсюда правило: будущее ставим всегда, бережём только прошедшее. */
const НЕПРИКОСНОВЕН_МИН = 3;

export function nextRingPlan(alarm, now = new Date()) {
    const настройка = normalizeAlarm(alarm);
    const ring = [];
    const silence = [];
    const keep = [];

    const положить = (key, hhmm, разрешено) => {
        if (!разрешено) { silence.push(key); return; }

        /* Час ТОЛЬКО ЧТО прошёл — не трогаем вовсе: ни ставим заново,
           ни снимаем. Пусть доживёт тот, что уже стоит в системе, и не
           уезжает на завтра из-за пересчёта. Будущее сюда не попадает:
           его надо ставить, а не беречь. */
        const минуты = minutesOfDay(hhmm);
        if (минуты !== null) {
            const сейчас = now.getHours() * 60 + now.getMinutes();
            const прошло = сейчас - минуты;
            if (прошло >= 0 && прошло <= НЕПРИКОСНОВЕН_МИН) { keep.push(key); return; }
        }

        const at = atNext(hhmm, now);
        if (at) ring.push({ key, at });
        else silence.push(key);
    };

    /* Оба часа под одной галочкой. Прежде у второго была своя, и
       выключена она была по умолчанию: названный человеком час молчал, а
       причину он найти не мог. Разбор — у normalizeAlarm выше. */
    /* Каждое направление — своё. 'off' снимает названный час совсем: он
       уходит в снятие, а не просто пропускается, потому что поставленный
       раньше звонок живёт в системе сам по себе. 'remind' час оставляет,
       но звонить он не будет — это решает ringsAsAlarm. */
    положить(KEY_NEXT_WINDOW, настройка.windowAt,
        настройка.on && настройка.windowMode !== 'off');
    положить(KEY_NEXT_MOMENTS, настройка.momentsAt,
        настройка.on && настройка.momentsMode !== 'off');

    return { ring, silence, keep };
}

/* НАЗВАННЫЙ ЧАС ЗВОНИТ КАЖДЫЙ ДЕНЬ, А НЕ ОДИН РАЗ.

   nextRingPlan ставит только ближайшее наступление часа. Прозвонил — и в
   системе пусто до тех пор, пока приложение не откроют и не переставят
   расписание. «Выключить» на экране будильника приложение не открывает,
   поэтому на следующий день звонка не было вовсе, и человек решал, что
   приложение сломано. Для часа, названного «каждый день в 13:00», это
   поломка, а не особенность.

   Приложение закрытым ставить будильники не умеет, поэтому ставим вперёд:
   ближайшее наступление уже поставил nextRingPlan, а здесь — копии на
   следующие days дней под ключами «+1», «+2» (см. baseKey). Открыли
   приложение — всё переставляется, ключи те же, лишнего не накапливается.

   Горизонт конечный, и это честно: после последней копии звонков нет,
   пока приложение не откроют. Бесконечно это умеет только нативная часть,
   но она хрупкая, и трогать её ради этого не стали.

   Ближайшее наступление считается ровно так же, как в nextRingPlan: только
   что прошедший час (в пределах НЕПРИКОСНОВЕН_МИН) остаётся сегодняшним, и
   копии отсчитываются от него — иначе завтрашний звонок пропал бы. */
export const ДНЕЙ_ВПЕРЁД = 2;

export function namedHorizon(alarm, now = new Date(), days = ДНЕЙ_ВПЕРЁД) {
    const настройка = normalizeAlarm(alarm);
    const ring = [];
    const silence = [];

    const один = (key, hhmm, разрешено) => {
        const ключи = Array.from({ length: days }, (_, i) => `${key}+${i + 1}`);
        const минуты = minutesOfDay(hhmm);

        // Нет часа или направление выключено — копии надо СНЯТЬ, а не
        // пропустить: поставленные вчера живут в системе сами по себе
        if (!разрешено || минуты === null) { silence.push(...ключи); return; }

        const прошло = now.getHours() * 60 + now.getMinutes() - минуты;
        const первое = прошло >= 0 && прошло <= НЕПРИКОСНОВЕН_МИН
            ? atToday(hhmm, now)
            : atNext(hhmm, now);
        if (!первое) { silence.push(...ключи); return; }

        ключи.forEach((копия, i) => {
            // setDate, а не +24 часа: на переходе на летнее время сутки не
            // равны 24 часам, и час звонка уехал бы
            const at = new Date(первое);
            at.setDate(at.getDate() + i + 1);
            ring.push({ key: копия, at });
        });
    };

    один(KEY_NEXT_WINDOW, настройка.windowAt,
        настройка.on && настройка.windowMode !== 'off');
    один(KEY_NEXT_MOMENTS, настройка.momentsAt,
        настройка.on && настройка.momentsMode !== 'off');

    return { ring, silence };
}

/* К какому направлению относится напоминание: 'window' (Наблюдатель),
   'moments' (Архитектор) или null — ключ незнакомый. */
export function sectionOf(key) {
    if (isWindowKey(key)) return 'window';
    if (baseKey(key) === KEY_NEXT_MOMENTS || String(key).startsWith(KEY_MOMENT)) return 'moments';
    return null;
}

/* ЧТО ДЕЛАТЬ С ЭТИМ НАПОМИНАНИЕМ: 'alarm', 'remind' или 'off'.

   Решает направление, к которому оно относится, а режим активности
   только сужает: он выключен — звонков нет нигде, но напоминания
   остаются. Он отвечает за ЗВОНОК, а не за существование напоминаний.

   'off' у направления сильнее всего: оно выключает и звонок, и
   напоминание. Незнакомый ключ — 'remind': будильник по ошибке хуже
   плашки по ошибке. */
export function modeOf(key, alarm) {
    const настройка = normalizeAlarm(alarm);
    const раздел = sectionOf(key);
    if (!раздел) return 'remind';

    const режим = раздел === 'window' ? настройка.windowMode : настройка.momentsMode;
    if (режим === 'off') return 'off';
    return настройка.on ? режим : 'remind';
}

/* ЧАСЫ, ОТ КОТОРЫХ ПЛЯШЕТ ДЕНЬ, ПО ВОЗРАСТАНИЮ.

   Человек называет два часа — по одному на направление. Каждый строит после
   себя свою фазу дня: утренний утро, обеденный день, вечерний вечер
   (выкладка 130). До неё в день уходил только последний из двух, и первый —
   скажем, «Наблюдателя» в 08:44 при «Архитекторе» в 14:30 — на утренних
   моментах не сказывался вовсе.

   ЭТО БЫЛО СЛОМАНО, И ВОТ КАК. views/quantum.js читал `alarm.moments` — поле
   второй галочки, которое я удалил в выкладке 116, не проверив все места,
   где его читали. Оно стало всегда undefined, и время «Архитектора» ни разу
   не попало в расчёт дня: две даты из двух направлений, одна работала, вторая
   молча отбрасывалась. Владелец увидел это раньше меня.

   Выключенное направление в расчёте не участвует: его часа нет ни в
   системе, ни на экране. Режим активности выключен — часов нет вовсе.
   Пустые часы не идут.

   Чистая функция, чтобы закрепить это тестами — в views/quantum.js, под
   браузером, её проверить было нечем. */
export function anchorHours(alarm) {
    const настройка = normalizeAlarm(alarm);
    if (!настройка.on) return [];

    return [
        настройка.windowMode === 'off' ? '' : настройка.windowAt,
        настройка.momentsMode === 'off' ? '' : настройка.momentsAt
    ].filter(Boolean).sort();
}

/* Звонит ли это напоминание будильником.

   Смотрим на ключ, а не на содержание: ключ — единственное, что у
   напоминания есть наверняка, и по нему видно, наше это напоминание или
   пришлое.

   В режиме активности звонит ВСЁ, о чём приложение знает: и окно
   возможностей, и девять моментов дня, и оба названных человеком часа.
   Прежде моменты дня требовали второй галочки — она и оказалась причиной
   беззвучных плашек (разбор у normalizeAlarm).

   Тихий час сюда не заглядывает, и правильно: заглушённое напоминание
   отмечено признаком quiet и до этой проверки не доходит вовсе (см.
   разметитьРежим в web/js/reminder-plan.js). */
export function ringsAsAlarm(key, alarm) {
    return modeOf(key, alarm) === 'alarm';
}

/* Окно возможностей: открывается через заданный срок после прыжка.

   Возвращаем null, когда ставить нечего, и у каждого «нечего» своя
   причина: прыжка ещё не было или окно уже открылось — звонить поздно.

   Тихий час в это число больше не входит. Он не снимает напоминание, а
   глушит его: приходит беззвучная плашка (разбор у momentPlan выше). */
export function windowPlan(lastJump, now = new Date(), options = {}) {
    const { cooldownMs = 0, windowMs = 0, quiet = null, off = false, named = '' } = options;

    // Наблюдатель выключен совсем: окно не ставится, а прежнее снимает
    // вызывающий (reminder-plan.js кладёт ключ в снятие, когда окна нет)
    if (off) return null;

    /* ЧАСЫ НАБЛЮДАТЕЛЯ (core/observer-clock.js, выкладка 148): опора цикла — прыжок или
       прозвучавший назначенный звонок. Ждём открытия — звоним в открытие; но если
       назначенный звонок раньше, он перезапустит цикл, и окно откроется через 3:33 после
       него. Окно открыто или прошло — следующее откроется после назначенного звонка. */
    const часы = observerClock({ lastJump, named, now: now.getTime(), cooldownMs, windowMs });
    let когда = 0;
    if (часы.phase === 'cooldown') {
        когда = часы.nextNamed && часы.nextNamed < часы.opens ? часы.nextNamed + cooldownMs : часы.opens;
    } else if (часы.phase !== 'never' && часы.nextNamed) {
        когда = часы.nextNamed + cooldownMs;
    }
    if (!когда) return null;

    const at = new Date(когда);
    if (at.getTime() <= now.getTime()) return null;

    return underQuiet(at, quiet)
        ? { key: KEY_WINDOW, at, quiet: true }
        : { key: KEY_WINDOW, at };
}

/* ПЛАШКА СТРАЖА: ЧТО НА НЕЙ НАПИСАНО В КАЖДЫЙ ЧАС ДНЯ.

   Плашка в шторке показывает два времени: когда человек может войти в
   суперпозицию Архитектором и когда — Наблюдателем. Времена меняются сами,
   по мере того как день идёт: наступил момент, кончилось его сорокаминутное
   окно, открылось окно возможностей, закрылось. Менять их должен тот, кто
   жив, когда приложение закрыто, — то есть страж на стороне Java.

   Но считать их на Java нельзя: расписание — это правила веб-слоя
   (activeMoment, nextMoment, окно после прыжка), и второй их пересказ на
   другом языке рано или поздно разойдётся с экраном. Владелец требовал
   обратного: время на плашке «строго соответствует» главному экрану.

   Поэтому веб-слой считает ВСЕ кадры дня заранее — по одному на каждую
   границу, на которой текст меняется, — и отдаёт их стражу списком.
   Страж ничего не вычисляет: берёт последний кадр, чей час наступил.
   Пересчитывается список при каждой перестановке расписания (открыли
   приложение, закрыли, прыгнули, погасили момент).

   Значения, как их понимает плашка:
     'ЧЧ:ММ' — войти можно после этого времени (для открытого окна — со
               времени, когда оно открылось);
     ''      — времени нет совсем (направление выключено или не известно ни
               одного звонка) — прочерк. Слов на месте часов не бывает
               (владелец 18.10.2026: «это часы, как там могут быть слова»).

   АРХИТЕКТОР — тот же момент, что подсвечен на главном экране: идущий
   сейчас, а если такого нет — ближайший (activeMoment, потом nextMoment, те
   самые функции, что рисуют экран).

   МОМЕНТЫ ДНЯ ПРОШЛИ — НЕ ПРОЧЕРК, А ПЕРВЫЙ ЗАВТРАШНИЙ (выкладка 143, просьба
   владельца 18.10.2026: «вместо прочерка показывать утро, а как сработает —
   следующее, перепрыгивать»). Часы завтрашних моментов телефон знает заранее:
   их считает retime по дате, человеку и тихому часу, и по этой заготовке
   (provisionalDay, options.tomorrow) уже стоят утренние звонки. Поэтому после
   последнего сегодняшнего момента Архитектор показывает первый завтрашний —
   тот, что и прозвонит, — а кадры после полуночи идут по заготовке: наступил
   момент — следующий. Когда откроют приложение и придёт настоящий день,
   кадры пересчитаются по нему.

   НАБЛЮДАТЕЛЬ — окно возможностей: открывается через cooldownMs после
   последнего прыжка и держится windowMs. Прыжка ещё не было — окно открыто
   (так же показывает его таймер в «Пространстве вариантов»).

   НАЗНАЧЕННЫЕ ЧАСЫ (выкладка 147, options.named). Владелец 18.10.2026 поставил
   в «Режиме будильника» Наблюдателю 16:00, сохранил — и «нигде не
   отобразилось»: звонок на 16:00 стоял, а плашка и виджеты писали прочерк, потому
   что считали только окно от прыжка и моменты дня. Названный час — тоже звонок
   этого направления, поэтому срок — ближайшее из вычисленного и названного:
   у Наблюдателя — открытие окна или его час, у Архитектора — момент дня или его
   час. Прочерк остаётся, только когда направление выключено или не известно
   никакого часа.

   ДЕНЬ ПРИ ВРЕМЕНИ. Срок не сегодня (относительно кадра) пишется с днём:
   значение «ЧЧ:ММ+1» — «завтра после ЧЧ:ММ» (guardTerm). Названный час
   ежедневный, завтрашние моменты — на завтра, поэтому дальше «завтра» срок не
   уходит. В полночь кадр сменяется, и «завтра» снимается само.

   @returns {{from: number, architect: string, observer: string}[]}
            по возрастанию from; у первого from равен 0 — «с самого начала» */
const СУТКИ_МС = 24 * 60 * 60 * 1000;

export function guardFrames(moments, lastJump, now = new Date(), options = {}) {
    const { cooldownMs = 0, windowMs = 0, architectOn = true, observerOn = true, tomorrow = [], named = {} } = options;

    const список = Array.isArray(moments) ? moments : [];
    const завтра = Array.isArray(tomorrow) ? tomorrow : [];
    // Полдень завтрашнего дня — опора для часов «ЧЧ:ММ» завтрашней заготовки
    const базаЗавтра = new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1, 12, 0, 0, 0);
    const сегодняшний = миг => new Date(миг).toDateString() === now.toDateString();
    const last = Number(lastJump);
    const прыгал = Number.isFinite(last) && last > 0;
    const откроется = last + cooldownMs;

    /* Срок словами для кадра: «ЧЧ:ММ», а если он на следующий день после кадра — «ЧЧ:ММ+1». */
    const срок = (когда, миг) => {
        const день = new Date(миг);
        день.setHours(0, 0, 0, 0);
        return когда.getTime() >= день.getTime() + СУТКИ_МС ? `${timeNow(когда)}+1` : timeNow(когда);
    };
    /* Ближайший приход ежедневного часа «ЧЧ:ММ» после мига (наступивший час — уже завтра). */
    const следующий = (hhmm, миг) => {
        if (!hhmm) return null;
        const когда = atToday(hhmm, new Date(миг));
        if (!когда) return null;
        if (когда.getTime() <= миг) когда.setDate(когда.getDate() + 1);
        return когда;
    };
    const раньше = (a, b) => (!a ? b : !b ? a : (a.getTime() <= b.getTime() ? a : b));

    /* Ближайший звонок дня после мига: следующий момент, после последнего — первый утренний
       завтра (заготовка), или назначенный час моментов, если он раньше. */
    const ближайшийЗвонок = миг => {
        const время = timeNow(new Date(миг));
        const день = сегодняшний(миг) ? список : завтра;
        const опора = сегодняшний(миг) ? now : базаЗавтра;
        let ближайший = null;
        const момент = nextMoment(день, время);
        if (момент) ближайший = atToday(момент.at, опора);
        else if (сегодняшний(миг)) {
            // Сегодня моментов больше нет — первый живой момент завтрашнего дня
            const первый = nextMoment(завтра, '');
            if (первый) ближайший = atToday(первый.at, базаЗавтра);
        }
        ближайший = раньше(ближайший, следующий(named.moments, миг));
        return ближайший ? срок(ближайший, миг) : '';
    };

    const архитектор = миг => {
        if (!architectOn) return '';
        // Идущий момент подсвечен на главном экране — он и есть срок
        const день = сегодняшний(миг) ? список : завтра;
        const идёт = activeMoment(день, timeNow(new Date(миг)));
        return идёт ? идёт.at : ближайшийЗвонок(миг);
    };

    /* ВО ВРЕМЯ ОТКРЫТОГО ОКНА ПИШЕМ ЧАС, КОГДА ОНО ОТКРЫЛОСЬ, А НЕ «СЕЙЧАС».
       Выкладки 125–128 писали «Наблюдателем — сейчас», и 17.10.2026 владелец
       прочёл это как «сейчас время звонка» и счёл глюком: слово ничего не
       говорит о том, ПОСЛЕ КАКОГО ЧАСА вход возможен, а он просил именно час.
       Теперь час стоит всегда — до открытия это будущее время, пока окно
       открыто — то, когда оно открылось («после 00:23», сейчас 01:00), и это
       тот же вид строки, что у Архитектора. Окно закрылось — прочерк. */
    /* Наблюдатель — часы Наблюдателя (core/observer-clock.js): тот же расчёт, что у таймера
       в «Пространстве» и в «Режиме будильника». Опоры нет — окно открыто с самого начала;
       окно открыто — час, когда открылось; иначе ближайший срок (открытие или звонок). */
    /* ВМЕСТО СЛОВ — ВРЕМЯ (выкладка 158). Владелец 18.10.2026: «никаких „окно открыто“ он не
       должен писать, там должно стоять время следующего звонка, оно всегда есть; последний звонок
       перед тихим часом — значит, утренний». Своего срока у Наблюдателя нет, когда опоры нет
       (не было ни прыжка, ни назначенного звонка — прежде «окно открыто») и когда окно прошло, а
       часа не назначено (прежде прочерк). Тогда — ближайший звонок дня, как у Архитектора после
       идущего момента: следующий момент, после последнего — первый утренний завтра. */
    const наблюдатель = миг => {
        if (!observerOn) return '';
        const часы = observerClock({ lastJump: прыгал ? last : 0, named: named.window, now: миг, cooldownMs, windowMs });
        if (часы.phase === 'open') return timeNow(new Date(часы.opens));
        if (часы.phase === 'cooldown' || часы.next) return срок(new Date(часы.next), миг);
        return ближайшийЗвонок(миг);
    };

    /* Границы, на которых текст может измениться: время каждого живого
       момента, конец его окна, открытие и закрытие окна возможностей. */
    const границы = new Set();
    for (const момент of список) {
        if (isOff(момент) || момент.doneAt) continue;

        const at = atToday(момент.at, now);
        if (!at) continue;

        границы.add(at.getTime());
        границы.add(at.getTime() + MOMENT_WINDOW_MINUTES * 60 * 1000);
    }
    // Те же границы у завтрашних моментов: после полуночи кадры перепрыгивают по ним
    for (const момент of завтра) {
        if (isOff(момент) || момент.doneAt) continue;

        const at = atToday(момент.at, базаЗавтра);
        if (!at) continue;

        границы.add(at.getTime());
        границы.add(at.getTime() + MOMENT_WINDOW_MINUTES * 60 * 1000);
    }
    if (observerOn && прыгал) {
        границы.add(откроется);
        границы.add(откроется + windowMs);
    }
    // Назначенные часы сегодня и завтра (прошёл — следующий) и полночь (снимается «завтра»)
    for (const hhmm of [named.window, named.moments]) {
        if (!hhmm) continue;
        const сегодня = atToday(hhmm, now);
        const завтрашний = atToday(hhmm, базаЗавтра);
        if (сегодня) границы.add(сегодня.getTime());
        if (завтрашний) границы.add(завтрашний.getTime());
    }
    // Назначенный звонок Наблюдателя перезапускает цикл: окно откроется и закроется после него
    if (observerOn && named.window) {
        for (const опора of [atToday(named.window, now), atToday(named.window, базаЗавтра)]) {
            if (!опора) continue;
            границы.add(опора.getTime() + cooldownMs);
            границы.add(опора.getTime() + cooldownMs + windowMs);
        }
    }
    границы.add(new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1, 0, 0, 0, 0).getTime());

    const порядок = [...границы]
        .filter(миг => миг > now.getTime())
        .sort((a, b) => a - b);

    const кадры = [];
    for (const from of [0, ...порядок]) {
        const кадр = {
            from,
            architect: архитектор(from === 0 ? now.getTime() : from),
            observer: наблюдатель(from === 0 ? now.getTime() : from)
        };

        // Подряд идущие одинаковые кадры — один: стражу незачем будить
        // плашку, когда читать на ней нечего нового
        const прежний = кадры[кадры.length - 1];
        if (прежний && прежний.architect === кадр.architect && прежний.observer === кадр.observer) {
            continue;
        }
        кадры.push(кадр);
    }
    return кадры;
}

/* ТЕКСТ ПЛАШКИ ПО КАДРУ.

   Три строки: вводная и по строке на каждое направление — столбиком, без
   разделителя между ними (так просил владелец 17.10.2026: прежняя одна
   строка «Архитектором … | Наблюдателем …» читалась хуже). Слова берутся из
   словаря через translate, который передаёт вызывающий: правило не знает ни
   языка человека, ни того, где хранится словарь. Порядок слов в каждой
   строке — часть перевода (ключи guard.lineArchitect и guard.lineObserver),
   а не кода: в другом языке роль и время могут стоять иначе.

   Страж на Java в свёрнутом виде не показывает ничего, кроме заголовка (так
   плашка занимает одну узкую строку), а весь этот текст виден при раскрытии. */
export function guardText(кадр, translate) {
    return [
        translate('guard.lead'),
        translate('guard.lineArchitect', { architect: guardTerm(кадр.architect, translate) }),
        translate('guard.lineObserver', { observer: guardTerm(кадр.observer, translate) })
    ].join('\n');
}

/* СРОК ОДНОГО НАПРАВЛЕНИЯ: «после 18:03», «завтра после 09:05» или «—». Слов вместо времени
   нет: прежнее значение 'now' («окно открыто», выкладки до 158) — тоже прочерк, если оно
   ещё лежит в старых кадрах.

   Вынесено из guardText: те же слова нужны виджетам на рабочем столе (раздел
   9.21), которым срок нужен отдельно от остального текста плашки. Слова берутся
   из тех же ключей, так что на виджете и на плашке написано одинаково. */
export function guardTerm(значение, translate) {
    if (!значение || значение === 'now') return translate('guard.none');
    // «ЧЧ:ММ+1» — срок на завтра (guardFrames): время пишется с днём
    const [time, завтра] = String(значение).split('+');
    return translate(завтра ? 'guard.afterTomorrow' : 'guard.after', { time });
}

/* ДЕНЬ, КОТОРЫЙ ЕЩЁ СЕГОДНЯШНИЙ.

   Приложение остаётся открытым через полночь: в памяти лежит вчерашний день,
   а часы «ЧЧ:ММ» его моментов планировщик привязывает к СЕГОДНЯШНЕЙ дате
   (atToday). Вчерашние девять моментов превращались в девять сегодняшних
   звонков в вчерашние часы — с чужими именами, которые настоящий день
   потом не снимал. Так в ночь на 17.10.2026 в системе набралось 32 звонка
   вместо 24: призраки стояли рядом с настоящими, и утром зазвонили бы дважды.

   День без даты считаем сегодняшним: так приходят и старые сохранения, и
   проверочные дни в тестах. День с другой датой — чужой, его как будто нет. */
export function freshDay(day, dateKey) {
    if (!day || !Array.isArray(day.moments)) return null;
    if (day.date && day.date !== dateKey) return null;
    return day;
}

/* КЛЮЧИ, КОТОРЫМИ РАСПОРЯЖАЕТСЯ РАСПИСАНИЕ.

   Всё, что ставит planReminders: моменты, окно возможностей, названные часы
   и их копии на следующие дни. Проверочные звонки («alarm-test…») сюда не
   входят — их ставит человек кнопкой, и расписание не вправе их снимать. */
export function isPlannedKey(key) {
    const base = baseKey(key);
    return base === KEY_WINDOW
        || base === KEY_NEXT_WINDOW
        || base === KEY_NEXT_MOMENTS
        || String(key).startsWith(KEY_MOMENT);
}

/* ЛИШНИЕ ЗВОНКИ: ЕСТЬ В СИСТЕМЕ, А В РАСПИСАНИИ ИХ НЕТ.

   Расписание само по себе снимает только то, о чём знает: ключи сегодняшнего
   дня, которые прожиты или погашены. Звонок с ключом, которого в нём больше
   нет (вчерашний день, момент, исчезнувший с сервера, заготовка не того дня),
   не снимал никто — он жил в системе и звонил. Здесь расписание сверяется с
   тем, что реально стоит: чужие ключи расписания — в снятие.

   standing — ключи, которые назвала система; planned — ключи, которые
   расписание ставит сейчас. */
export function orphanKeys(standing, planned) {
    const нужные = new Set(planned);
    return [...new Set(standing)].filter(key => isPlannedKey(key) && !нужные.has(key));
}
