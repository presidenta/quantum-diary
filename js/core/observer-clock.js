/* ЧАСЫ НАБЛЮДАТЕЛЯ — ЕДИНЫЙ РАСЧЁТ ОКНА ВОЗМОЖНОСТЕЙ (выкладка 148).

   ТЗ владельца 18.10.2026: таймер в «Режиме будильника», виджеты, плашка в шторке и
   таймер «До возможного следующего прыжка» в «Пространстве» показывают одно и то же
   время, посчитанное в одном месте. До этой выкладки каждый считал сам: таймер — от
   последнего прыжка, кадры плашки — от прыжка и назначенного часа, звонок «окно
   открыто» — от прыжка. Ни один не знал, что назначенный звонок перезапускает цикл.

   ПРАВИЛО ЦИКЛА.
   Опора цикла — последнее из двух событий: прыжок (переход в суперпозицию, а также
   сброс пропущенного окна в «Пространстве») или прозвучавший назначенный звонок
   Наблюдателя («Окно возможностей — Наблюдатель» в «Режиме будильника», например
   16:00). От опоры через cooldownMs (3 ч 33 мин) открывается окно возможностей и
   держится windowMs.
   «Явный будильник» (ТЗ п. 2.3): назначенный час, пока он впереди, — ближайший срок,
   если он раньше открытия окна: в 15:30 при 16:00 таймер показывает 00:30:00. Наступил
   — звонок звенит, опора переезжает на 16:00, и таймер сразу считает до 19:33.

   Назначенный час ежедневный (так его и ставит расписание: alarm-next-window и копии
   на следующие дни), поэтому «прозвучавший» — последний его приход, не позже «сейчас»:
   сегодняшний, а если он ещё впереди — вчерашний.

   Чистые функции: время приходит параметром, ничего не читается из хранилища — так
   правило одно и то же в браузере, в тестах и для каждого кадра плашки. */

const МИНУТА_МС = 60 * 1000;

/* «ЧЧ:ММ» в минуты от полуночи; негодное — null. */
function минутыЧаса(hhmm) {
    const м = /^(\d{1,2}):(\d{2})$/.exec(String(hhmm || '').trim());
    if (!м) return null;
    const ч = Number(м[1]);
    const мин = Number(м[2]);
    return ч > 23 || мин > 59 ? null : ч * 60 + мин;
}

/* Приход часа «ЧЧ:ММ» в тот же день, что миг, в миллисекундах. */
function вТотЖеДень(минуты, миг) {
    const день = new Date(миг);
    день.setHours(0, 0, 0, 0);
    return день.getTime() + минуты * МИНУТА_МС;
}

/* ТИХИЙ ЧАС (выкладка 160). Владелец 18.10.2026: прыгнул в 23:03 — и таймер, плашка и звонок
   показали окно в 02:36, посреди тишины 23:00–06:00. «Если тихий час — в это время звонить
   телефон не может, кроме лично наведённого будильника; окно автоматически переходит на утро».
   Окно, которое открылось бы в тихий час, открывается с её концом и держится windowMs оттуда.
   Назначенный час — личный будильник человека: тишина его не двигает. */

/** Миг, перенесённый за тихий час: попал в тишину — её конец, иначе как есть. */
export function afterQuiet(миг, quiet) {
    if (!quiet || quiet.on === false || !миг) return миг;
    const с = минутыЧаса(quiet.from);
    const до = минутыЧаса(quiet.until);
    if (с === null || до === null || с === до) return миг;
    const день = new Date(миг);
    const минуты = день.getHours() * 60 + день.getMinutes();
    const тихо = с > до ? (минуты >= с || минуты < до) : (минуты >= с && минуты < до);
    if (!тихо) return миг;
    const конец = new Date(вТотЖеДень(до, миг));
    if (конец.getTime() <= миг) конец.setDate(конец.getDate() + 1);
    return конец.getTime();
}

/** Последний приход ежедневного часа не позже мига; часа нет — 0. */
export function lastNamedAt(hhmm, миг) {
    const минуты = минутыЧаса(hhmm);
    if (минуты === null) return 0;
    const сегодня = вТотЖеДень(минуты, миг);
    if (сегодня <= миг) return сегодня;
    const вчера = new Date(сегодня);
    вчера.setDate(вчера.getDate() - 1);
    return вчера.getTime();
}

/** Следующий приход ежедневного часа строго после мига; часа нет — 0. */
export function nextNamedAt(hhmm, миг) {
    const минуты = минутыЧаса(hhmm);
    if (минуты === null) return 0;
    const сегодня = вТотЖеДень(минуты, миг);
    if (сегодня > миг) return сегодня;
    const завтра = new Date(сегодня);
    завтра.setDate(завтра.getDate() + 1);
    return завтра.getTime();
}

/**
 * Состояние окна возможностей на миг.
 *
 * @param {object} p
 * @param {number} p.lastJump   время последнего прыжка, мс (0 — прыжка не было)
 * @param {string} p.named      назначенный час Наблюдателя «ЧЧ:ММ» или '' (выключен)
 * @param {number} p.now        миг, мс
 * @param {number} p.cooldownMs через сколько после опоры открывается окно
 * @param {number} p.windowMs   сколько окно держится
 * @param {{on: boolean, from: string, until: string}} [p.quiet] тихий час: окно в нём — с его концом
 * @param {number} [p.setAt]    когда час Наблюдателя назначили вручную, мс (0 — не знаем): назначенное
 *                              после последней опоры и позже расчётного окна — ближайший срок, см. РУЧНОЙ ЧАС
 * @returns {{phase: 'never'|'cooldown'|'open'|'missed', anchor: number, opens: number,
 *            closes: number, nextNamed: number, next: number}}
 *   phase  — never: опоры нет (не было ни прыжка, ни звонка) — окно открыто с начала;
 *            cooldown: ждём открытия; open: окно открыто; missed: окно прошло;
 *   next   — ближайший срок Наблюдателя после мига (открытие окна или назначенный звонок),
 *            0 — неизвестен (окно открыто или прошло, а часа не назначено).
 */
export function observerClock({ lastJump = 0, named = '', now, cooldownMs, windowMs, quiet = null, setAt = 0 }) {
    const прыжок = Number(lastJump) > 0 ? Number(lastJump) : 0;
    const опора = Math.max(прыжок, lastNamedAt(named, now));
    const nextNamed = nextNamedAt(named, now);

    if (!опора) {
        return { phase: 'never', anchor: 0, opens: 0, closes: 0, nextNamed, next: 0 };
    }
    const opens = afterQuiet(опора + cooldownMs, quiet);
    const closes = opens + windowMs;

    /* РУЧНОЙ ЧАС ПЕРЕНОСИТСЯ НА ЭКРАН СРАЗУ (выкладка 164). Владелец 19.10.2026 в 20:21: окно
       открылось в 19:12, он назначил Наблюдателю 21:00 — а на виджете осталось «после 19:12».
       Расчёт брал «что раньше» из назначенного часа и окна от прыжка, и час позже окна терялся.
       Но назначенный вручную час — решение человека: «время переносится на экран автоматически, и
       с него начинается отсчёт следующего звонка; а если тихий час — считает после 6 утра».
       Поэтому час, назначенный ПОСЛЕ последней опоры цикла (прыжка или прозвучавшего звонка) и
       позже расчётного открытия, вытесняет это открытие: ближайший срок — он сам; прозвенел —
       опора переезжает на него, окно откроется через cooldownMs (с учётом тихого часа). Прыжок
       после назначения или сам звонок снимают правило: цикл снова идёт от последней опоры. */
    if (named && Number(setAt) > опора && nextNamed > opens) {
        const открытие = afterQuiet(nextNamed + cooldownMs, quiet);
        return {
            phase: 'cooldown', anchor: nextNamed, opens: открытие, closes: открытие + windowMs,
            nextNamed, next: nextNamed, manual: true
        };
    }

    if (now < opens) {
        const next = nextNamed && nextNamed < opens ? nextNamed : opens;
        return { phase: 'cooldown', anchor: опора, opens, closes, nextNamed, next };
    }
    return { phase: now < closes ? 'open' : 'missed', anchor: опора, opens, closes, nextNamed, next: nextNamed };
}

/* ЧАС НАБЛЮДАТЕЛЯ СЛЕДУЕТ ЗА ЦИКЛОМ (выкладка 157).

   Владелец 18.10.2026: «везде должно быть одинаковое время». В «Режиме будильника» стоял
   назначенный час 17:30, а плашка и виджеты — «после 21:14»: звонок в 17:30 прозвенел, потом был
   прыжок в 17:41, и цикл ушёл дальше. По ТЗ («таймер сбрасывается и пересчитывает следующее окно,
   время мгновенно транслируется везде») назначенный час после своего звонка переезжает на
   открытие следующего окна — и в настройках то же время, что на виджете.

   Переезжает, только если он уже прозвенел ПОСЛЕ того, как его назначили (setAt): час, который
   человек только что поставил на вечер, ещё не звонил и остаётся, как поставлен. И только пока
   окно впереди (cooldown): открытое или прошедшее окно часа не даёт.

   @returns {string} новый час «ЧЧ:ММ» или '' — оставить как есть */
export function cycleNamedHour({ named = '', setAt = 0, lastJump = 0, now, cooldownMs, windowMs, quiet = null }) {
    if (!named) return '';
    const прозвучал = lastNamedAt(named, now);
    if (!прозвучал || прозвучал < setAt) return '';

    const часы = observerClock({ lastJump, named, now, cooldownMs, windowMs, quiet });
    if (часы.phase !== 'cooldown') return '';
    const открытие = new Date(часы.opens);
    const час = `${String(открытие.getHours()).padStart(2, '0')}:${String(открытие.getMinutes()).padStart(2, '0')}`;
    return час === named ? '' : час;
}

/** «ЧЧ:ММ:СС» до мига или от мига (по модулю): для таймеров обратного отсчёта. */
export function countdownText(ms) {
    const всего = Math.max(0, Math.floor(Math.abs(ms) / 1000));
    const ч = String(Math.floor(всего / 3600)).padStart(2, '0');
    const м = String(Math.floor((всего % 3600) / 60)).padStart(2, '0');
    const с = String(всего % 60).padStart(2, '0');
    return `${ч}:${м}:${с}`;
}
