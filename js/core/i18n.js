/* Перевод по ключу. Подстановки — {имя} в тексте: t('day.inDays', { n: 3 }).
   Нет перевода на этом языке — берём русский; нет и там — отдаём сам ключ,
   чтобы пропажа была видна при проверке, а не молчала пустым местом. */
export function translate(language, key, values) {
  const text = DICT[language]?.[key] ?? DICT[DEFAULT_LANGUAGE][key] ?? key;
  if (!values) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name) =>
    (Object.hasOwn(values, name) ? String(values[name]) : whole));
}

// Язык из настроек человека, из браузера или русский
export function pickLanguage(saved, navigatorLanguages = []) {
  if (isLanguage(saved)) return saved;
  for (const entry of navigatorLanguages) {
    const code = String(entry).slice(0, 2).toLowerCase();
    if (isLanguage(code)) return code;
  }
  return DEFAULT_LANGUAGE;
}

// Ключи, которых не хватает в языке, — для проверки полноты словаря
export const missingKeys = language =>
  Object.keys(DICT[DEFAULT_LANGUAGE]).filter(k => !(k in (DICT[language] || {})));

export const dictionary = language => DICT[language] || {};
