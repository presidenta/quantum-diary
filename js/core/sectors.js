/* СФЕРЫ ЖИЗНИ ПО УМОЛЧАНИЮ: кто они и когда их создавать.

   Чистые правила без браузера и хранилища — под тестами
   (test/sectors.test.js). Запись в базу и чтение состояния живут этажом
   выше, в js/store.js и js/app.js.

   ПОЧЕМУ ЭТОТ ФАЙЛ ПОЯВИЛСЯ. Девять сфер по умолчанию создавало каждое
   устройство само, со своими случайными id. Устройство, на котором сфер
   нет, засевало их, даже если у учётной записи они уже были, — и при
   следующей синхронизации наборы СКЛАДЫВАЛИСЬ, а не сливались: id разные,
   значит для сервера это разные записи. На экране вместо семи–девяти сфер
   оказывалось четырнадцать–восемнадцать.

   Отсюда два правила ниже, и оба нужны:

     1. id сферы по умолчанию ОДИНАКОВ на всех устройствах. Два устройства,
        засеявшие сферы независимо, напишут одни и те же девять записей, и
        синхронизация их сольёт, а не сложит.
     2. Засевать только тогда, когда известно, что у учётной записи сфер
        нет. Пока это не выяснено — не создавать ничего: создать легко,
        а отличить потом свою заготовку от настоящей сферы человека
        нельзя. */

// Названия по умолчанию — ключи словаря: при смене языка меняются и они,
// пока человек не переименовал сферу сам
export const DEFAULT_SECTOR_KEYS = [
  'sector.health', 'sector.career', 'sector.money', 'sector.family',
  'sector.people', 'sector.growth', 'sector.joy', 'sector.spirit', 'sector.home'
];

// Сколько сфер включено сразу. Всего их девять, человек оставляет 7, 8 или 9
export const DEFAULT_COUNT = 8;

/* Устойчивый id сферы по умолчанию.
 *
 * Не случайный нарочно — в этом вся починка. Вид записи обычный uuid
 * (сервер проверяет формат, а столбец в базе типа uuid), но собран он
 * из слота, а не из случайных чисел: слот 3 на любом устройстве и у
 * любого человека даёт один и тот же id.
 *
 * Делить id между людьми можно: в базе первичный ключ — пара
 * (user_id, id), и сферы разных людей не сталкиваются.
 *
 * «5ec7» в начале читается как sect(or) — чтобы такой id в журнале или в
 * базе сразу узнавался и не выглядел порчей данных. */
export function defaultSectorId(slot) {
  if (!Number.isInteger(slot) || slot < 1 || slot > 9) {
    throw new Error(`слот сферы бывает от 1 до 9, получен: ${slot}`);
  }
  return `5ec70000-0000-4000-8000-00000000000${slot}`;
}

/* Время правки у заготовки — начало эпохи.
 *
 * Спор решается по более позднему updatedAt: и на сервере (upsert идёт
 * только WHERE updated_at < EXCLUDED.updated_at), и при слиянии на
 * устройстве. Поставь заготовке сегодняшнее время — и она перебьёт
 * настоящую сферу человека, затерев название, которое он придумал.
 * С началом эпохи заготовка не перебивает ничего и уходит на сервер
 * только тогда, когда там ещё пусто. */
export const SEED_STAMP = '1970-01-01T00:00:00.000Z';

/**
 * Девять сфер по умолчанию.
 *
 * @param {(key: string) => string} nameFor перевод ключа названия
 * @returns {Array<object>} записи, готовые к записи в базу
 */
export function defaultSectors(nameFor) {
  return DEFAULT_SECTOR_KEYS.map((key, i) => {
    const slot = i + 1;
    return {
      id: defaultSectorId(slot),
      slot,
      name: nameFor(key),
      position: slot,
      active: slot <= DEFAULT_COUNT,
      paused: false,
      updatedAt: SEED_STAMP,
      deletedAt: null
    };
  });
}

/* ПОРА ЛИ ЗАСЕВАТЬ.
 *
 * Три условия, и ни одно нельзя выбросить:
 *
 *   sectorCount === 0 — сферы уже есть, создавать нечего;
 *   accountKnown     — мы выяснили, что у учётной записи на сервере. Без
 *                      этого засев и есть та самая поломка: устройство
 *                      создаёт второй набор к тому, что уже лежит на
 *                      сервере;
 *   signedIn         — до входа учётной записи просто нет, и выяснять
 *                      нечего.
 *
 * Закрытая регистрация делает это условие бесплатным: учётную запись
 * выдаёт сервер, и пользоваться приложением, ни разу до него не
 * добравшись, всё равно нельзя. Значит отложить засев до первой удачной
 * синхронизации мы ничего не теряем — зато не создаём данные, которые
 * потом придётся сводить.
 */
export function shouldSeed({ signedIn, accountKnown, sectorCount }) {
  return Boolean(signedIn) && Boolean(accountKnown) && sectorCount === 0;
}

/* СХЛОПНУТЬ ДУБЛИ СФЕР.

   Откуда они взялись. Пока у заготовок был случайный id, каждое
   устройство создавало свой набор, и на экране «Колесо» сферы шли
   парами: «Здоровье и спорт» дважды, «Карьера и дело» дважды — всего
   восемнадцать вместо девяти. Сами заготовки починены (см.
   defaultSectorId), но уже наделанные дубли от этого не исчезают: они
   лежат на устройстве и на сервере.

   ПОЧЕМУ НЕ ПРОСТО «УДАЛИТЬ ЛИШНЕЕ». К сфере привязаны цели, и если
   убрать ту, на которую они ссылаются, человек потеряет их молча.
   Поэтому из пары остаётся та, которой пользуются: сначала смотрим, на
   чей id ссылаются цели, потом на более позднюю правку, и лишь в
   последнюю очередь — на заготовочный id, чтобы будущие засевы
   совпадали с оставшейся.

   Лишние не стираются, а помечаются удалёнными: так их уносит обычная
   синхронизация, и то же решение доезжает до других устройств. */
export function dedupeSectors(sectors, usedIds = new Set(), now = new Date().toISOString()) {
  const живые = (sectors || []).filter(s => s && !s.deletedAt);
  const группы = new Map();

  for (const s of живые) {
    // Ключ — название: дубли различаются только идентификатором
    const ключ = String(s.name || '').trim().toLowerCase() || `слот-${s.slot}`;
    if (!группы.has(ключ)) группы.set(ключ, []);
    группы.get(ключ).push(s);
  }

  const лишние = [];

  for (const [, пара] of группы) {
    if (пара.length < 2) continue;

    const оставить = выбратьГлавную(пара, usedIds);
    for (const s of пара) {
      if (s.id === оставить.id) continue;
      лишние.push({ ...s, deletedAt: now, updatedAt: now });
    }
  }

  return лишние;
}

/* Какая из пары — настоящая.

   Порядок проверок именно такой и менять его нельзя: цели важнее
   свежести правки, а свежесть важнее красоты идентификатора. */
function выбратьГлавную(пара, usedIds) {
  const сЦелями = пара.filter(s => usedIds.has(s.id));
  if (сЦелями.length === 1) return сЦелями[0];

  const список = сЦелями.length > 1 ? сЦелями : пара;

  const позже = [...список].sort((a, b) =>
    String(b.updatedAt || '').localeCompare(String(a.updatedAt || '')));

  // Правки одинаково свежи — берём ту, что совпадает с заготовкой:
  // тогда будущий засев не создаст третью
  const свежесть = String(позже[0].updatedAt || '');
  const равные = позже.filter(s => String(s.updatedAt || '') === свежесть);
  if (равные.length === 1) return равные[0];

  const заготовка = равные.find(s => {
    try { return s.id === defaultSectorId(s.slot); } catch { return false; }
  });
  return заготовка || равные[0];
}
