/* ЖУРНАЛ САМОГО УСТРОЙСТВА В БРАУЗЕРЕ И В ПРИЛОЖЕНИИ ДЛЯ КОМПЬЮТЕРА (выкладка 162).

   Владелец 19.10.2026: «Логи» на компьютере были пустыми, а у телефона журнал есть. Задание:
   «чтобы работали точно так же, как на телефоне, только собирали свои логи с компьютера —
   администратор должен видеть, какие там ошибки». Журнал телефона ведёт нативная часть
   (AlarmStore), и о компьютере он ничего не знает. Этот журнал — компьютера: те же записи
   { t — когда, e — знак, k — имя, a — час, n — число } и тот же вид экрана (alarm-journal.js),
   плюс текст сообщения m — у ошибок и сбоев он главное.

   Хранится в localStorage: окно «Кванта» и окна виджетов (это одна сессия Electron) пишут в
   один и тот же журнал. Кольцо в LIMIT записей и MAX_AGE_MS, чтобы журнал не рос вечно.
   Запись журнала не вправе ничего сломать: любой сбой хранилища (приватный режим, переполнение)
   молча проглатывается — это улика, а не работа.

   ЗНАКИ КОМПЬЮТЕРА (расшифровка — alarm.webHint в словаре):
     START  «Квант» открыт (m — версия и где открыт)
     E      ошибка в коде или сбой загрузки (m — текст; подряд одинаковые — одной строкой с числом)
     S      синхронизация принесла новое (n — сколько записей)
     S✗     синхронизация не удалась (m — причина)
     AUTH   вход пропал — нужен вход заново
     ⇄      настройки с другого устройства приняты (m — какие)
     V      виджетам положены сроки на день (n — кадров, a — ближайший срок)
     V✗     сроки виджетам не посчитались (m — причина)
     D      виджет на столе показал другое (k — вид, m — «Архитектор | Наблюдатель»)
     ⤴      прыжок совершён: окно закрыто, цикл пошёл заново
     ◎      окно возможностей открылось в приложении
     NET    сеть пропала или вернулась (m) */

export const JOURNAL_KEY = 'kvant-web-journal';
export const LIMIT = 400;
export const MAX_AGE_MS = 7 * 24 * 60 * 60 * 1000;
const MAX_TEXT = 300;

/**
 * Добавить запись к журналу — чистая функция.
 *
 * Подряд идущие одинаковые ошибки (знак, имя и текст те же) складываются в одну запись с числом
 * n: зациклившаяся ошибка не вытеснит остальное. Старше недели и сверх предела — отбрасывается.
 */
export function addEntry(список, запись, now = Date.now(), предел = LIMIT) {
    const журнал = Array.isArray(список) ? список.slice() : [];
    const новая = { t: now, e: String(запись.e) };
    if (запись.k) новая.k = String(запись.k).slice(0, 80);
    if (запись.a) новая.a = Number(запись.a);
    if (запись.n) новая.n = Number(запись.n);
    if (запись.m) новая.m = String(запись.m).replace(/\s+/g, ' ').trim().slice(0, MAX_TEXT);

    const прежняя = журнал[журнал.length - 1];
    if (прежняя && прежняя.e === новая.e && прежняя.k === новая.k && прежняя.m === новая.m
        && (новая.e === 'E' || новая.e === 'S✗' || новая.e === 'NET')) {
        журнал[журнал.length - 1] = { ...прежняя, t: now, n: (прежняя.n || 1) + 1 };
    } else {
        журнал.push(новая);
    }
    return журнал.filter(з => now - з.t <= MAX_AGE_MS).slice(-предел);
}

/** Записать событие в журнал этого устройства. Никогда не бросает. */
export function logEvent(знак, поля = {}) {
    try {
        const прежний = JSON.parse(localStorage.getItem(JOURNAL_KEY) || '[]');
        localStorage.setItem(JOURNAL_KEY, JSON.stringify(addEntry(прежний, { e: знак, ...поля })));
    } catch {
        /* хранилища нет или оно полно — журнал не ведётся, приложение живёт */
    }
}

/** Журнал этого устройства: старые сверху. Нет или испорчен — пустой. */
export function readJournal() {
    try {
        const журнал = JSON.parse(localStorage.getItem(JOURNAL_KEY) || '[]');
        return Array.isArray(журнал) ? журнал : [];
    } catch {
        return [];
    }
}
