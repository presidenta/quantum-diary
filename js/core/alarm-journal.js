/* ЖУРНАЛ ЗВОНКОВ: КАК ОН ВЫГЛЯДИТ НА ЭКРАНЕ «ЛОГИ».

   Нативная часть пишет события одним потоком: «+» поставлен, «✓» сработал,
   «!» не дошёл, «G+» страж встал и так далее (AlarmStore.журнал). Здесь они
   превращаются в строки, которые человек присылает скриншотом, и по которым
   потом решается, что сломано. Поэтому главное требование к ним — чтобы по
   одному скриншоту было понятно, КАКОЙ звонок, на КАКОЙ час и не ПОЗДНО ли.

   Вынесено из app.js, потому что там это нечем было проверить, а ошибка
   читаемости здесь обходится дорого: 16.10.2026 на скриншоте владельца все
   четырнадцать строк были «G+» и «+», и какие пять звонков не дошли — прочесть
   было нельзя. Шум вытеснил улику.

   Запись журнала: { t — когда записано, e — знак, k — ключ звонка,
   a — на какой час был назначен (0 — не применимо), n — число }. */

const два = n => String(n).padStart(2, '0');

const часы = ms => {
    const d = new Date(ms);
    return `${два(d.getHours())}:${два(d.getMinutes())}:${два(d.getSeconds())}`;
};

const сутки = ms => {
    const d = new Date(ms);
    return `${два(d.getDate())}.${два(d.getMonth() + 1)}`;
};

/* Опоздание меньше этого — обычная погрузка приёмника, показывать нечего. */
const ОПОЗДАНИЕ_ЗАМЕТНОЕ_СЕК = 3;

/* Час, на который назначен звонок. Если он выпадает на другие сутки, чем
   сама запись, — с датой: «завтра в 20:45» и «сегодня в 20:45» без неё
   неотличимы, а на скриншоте 23:37 как раз стояли завтрашние звонки.

   Связка — стрелка «→» (на какой час назначено). У «☠» это «в»: там час —
   не назначение, а когда умер процесс, и «☠ … → 02:14» читалось бы как
   «умрёт в 02:14». */
function назначено(запись, связка = '→') {
    if (!запись.a) return '';
    const другойДень = сутки(запись.a) !== сутки(запись.t);
    return ` ${связка} ${другойДень ? `${сутки(запись.a)} ` : ''}${часы(запись.a)}`;
}

/**
 * @param {Array<{t:number,e:string,k?:string,a?:number,n?:number}>} журнал
 * @returns {string} строки через перевод строки, старые сверху
 */
export function formatJournal(журнал) {
    if (!Array.isArray(журнал)) return '';

    /* ПАЧКА «+» ОДНОЙ СТРОКОЙ. Переставили расписание — и на каждый звонок
       по строке «поставлен». Пятнадцать одинаковых строк подряд ничего не
       говорят, а место занимают всё. Сворачиваем подряд идущие «+» в одну с
       числом; одиночный «+» остаётся с именем и часом. */
    const строки = [];
    for (const запись of журнал) {
        const прежняя = строки[строки.length - 1];
        if (запись.e === '+' && прежняя && прежняя.запись.e === '+') {
            прежняя.число += 1;
            continue;
        }
        строки.push({ запись, число: 1 });
    }

    return строки.map(({ запись, число }) => {
        const начало = `${часы(запись.t)}  ${запись.e}`;

        if (запись.e === '+' && число > 1) return `${начало} ×${число}`;

        const ключ = запись.k ? ` ${запись.k}` : '';
        const куда = назначено(запись, запись.e === '☠' ? 'в' : '→');

        /* У «✓» и «B» поле n — это опоздание в секундах (AlarmReceiver):
           сигнал пришёл на столько позже назначенного. Это отличает «вовремя»
           от «когда телефон проснулся». У остальных знаков n — просто число. */
        let хвост = '';
        if (запись.e === '✓' || запись.e === 'B') {
            if (запись.n >= ОПОЗДАНИЕ_ЗАМЕТНОЕ_СЕК) хвост = ` (позже на ${запись.n} с)`;
        } else if (запись.n) {
            хвост = ` ×${запись.n}`;
        }

        return `${начало}${ключ}${куда}${хвост}`;
    }).join('\n');
}

/* ЧТО СЕЙЧАС СТОИТ В СИСТЕМЕ — СПИСКОМ.

   «Поставлено звонков: 32» ничего не говорит, пока не знаешь, должно ли быть
   тридцать два. 17.10.2026 их оказалось на восемь больше, чем нужно:
   девять «призраков» вчерашнего дня стояли рядом с настоящими. Увидеть это
   можно было только расчётом по коду. Список с ключом и часом показывает
   такое с одного взгляда.

   Отсортирован по часу. Длинный хвост обрезается, чтобы окно не росло
   бесконечно, но число оставшихся называется.

   @param {Array<{key: string, at: number}>} alarms
   @param {number} [предел] сколько строк показывать */
export function formatPending(alarms, предел = 40) {
    if (!Array.isArray(alarms)) return '';

    const по = [...alarms].sort((a, b) => (a.at || 0) - (b.at || 0));
    const строки = по.slice(0, предел).map(a =>
        `${сутки(a.at)} ${часы(a.at).slice(0, 5)}  ${a.key}`);

    if (по.length > предел) строки.push(`… ещё ${по.length - предел}`);
    return строки.join('\n');
}

/* ГРУППА ОЖИДАНИЯ ПРИЛОЖЕНИЯ — ИМЕНЕМ ИЗ ДОКУМЕНТАЦИИ ANDROID.

   Число приходит из нативной части (UsageStatsManager.getAppStandbyBucket).
   Имена не переводятся: окно «Логи» — для разбора, его пересылают скриншотом,
   и английское название ищется в документации одним запросом. Нужна группа
   затем, что ОГРАНИЧЕННОЕ (RESTRICTED) приложение система лишает фоновой
   работы и точных сигналов, даже когда «батарея без ограничений».

   Неизвестное число и ноль (старый Android) — пустая строка: говорить
   нечего. */
const ГРУППЫ = Object.freeze({
    5: 'EXEMPTED', 10: 'ACTIVE', 20: 'WORKING_SET', 30: 'FREQUENT',
    40: 'RARE', 45: 'RESTRICTED', 50: 'NEVER'
});

export function standbyName(число) {
    return ГРУППЫ[Number(число)] || '';
}
