/* Что делать с копией данных на телефоне, когда кто-то входит.

   Тот же человек (или устройство, где ещё никто не входил) — данные и курсор
   остаются: не нужно заново скачивать то, что уже есть, а правки, сделанные
   без сети, дождутся отправки.

   Другой человек — копию надо стереть ДО старта приложения. Иначе он увидит
   на экране чужие сферы и цели, а неотправленные правки предыдущего уйдут
   на сервер уже под его учётной записью. */
export function sessionChange(previousUserId, nextUserId) {
  return previousUserId && previousUserId !== nextUserId ? 'clear' : 'keep';
}
